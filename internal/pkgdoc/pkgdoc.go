// Package pkgdoc generates the package reference (docs/registry) from the
// package files in registry/. The documentation lives in each package's doc
// section, so it travels with the package; this only renders it.
package pkgdoc

import (
	"fmt"
	"io/fs"
	"os"
	"path"
	"path/filepath"
	"sort"
	"strings"

	"github.com/DominicThemiya/Packenger/internal/pkgfile"
)

// Tree is every package in a registry directory.
type Tree struct {
	Pkgs map[string]*pkgfile.File // by name, e.g. "std/if"
}

// Load reads every .pkg file under dir.
func Load(dir string) (*Tree, error) {
	t := &Tree{Pkgs: map[string]*pkgfile.File{}}
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || !strings.HasSuffix(p, ".pkg") {
			return err
		}
		rel, _ := filepath.Rel(dir, p)
		name := strings.TrimSuffix(filepath.ToSlash(rel), ".pkg")
		src, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		f, err := pkgfile.Parse(name, "registry/"+name+".pkg", string(src))
		if err != nil {
			return err
		}
		t.Pkgs[name] = f
		return nil
	})
	return t, err
}

func (t *Tree) names() []string {
	out := make([]string, 0, len(t.Pkgs))
	for n := range t.Pkgs {
		out = append(out, n)
	}
	sort.Strings(out)
	return out
}

// Check reports packages without docs, truck members that do not exist,
// and packages that belong to no truck.
func (t *Tree) Check() []string {
	var problems []string
	inTruck := map[string]bool{}
	for _, n := range t.names() {
		f := t.Pkgs[n]
		if f.Doc == "" {
			problems = append(problems, fmt.Sprintf("%s has no doc summary", n))
		}
		for _, m := range f.Truck {
			full := n + "/" + m
			if _, ok := t.Pkgs[full]; !ok {
				problems = append(problems, fmt.Sprintf("truck %s lists %s, which does not exist", n, full))
			}
			inTruck[full] = true
		}
		for _, need := range f.Needs {
			if _, ok := t.Pkgs[need]; !ok {
				problems = append(problems, fmt.Sprintf("%s needs %s, which does not exist", n, need))
			}
		}
	}
	for _, n := range t.names() {
		if strings.Contains(n, "/") && !inTruck[n] {
			problems = append(problems, fmt.Sprintf("%s is not listed in its truck %s", n, path.Dir(n)))
		}
	}
	return problems
}

// Generate renders the reference: a map from path (relative to the
// output directory) to file contents.
func (t *Tree) Generate() map[string]string {
	out := map[string]string{"README.md": t.index()}
	for _, n := range t.names() {
		out[n+".md"] = t.page(n)
	}
	return out
}

func header(source string) string {
	return fmt.Sprintf("<!-- Generated by `go run ./cmd/pkgdoc`. Edit %s instead. -->\n\n", source)
}

// link returns a relative Markdown link from page "from" to package "to".
func link(from, to string) string {
	rel, _ := filepath.Rel(path.Dir(from), to+".md")
	return fmt.Sprintf("[%s](%s)", to, filepath.ToSlash(rel))
}

func (t *Tree) roots() []string {
	member := map[string]bool{}
	for _, n := range t.names() {
		for _, m := range t.Pkgs[n].Truck {
			member[n+"/"+m] = true
		}
	}
	var out []string
	for _, n := range t.names() {
		if !member[n] {
			out = append(out, n)
		}
	}
	// front-end trucks (syntax) before back-end trucks (emit)
	backend := func(n string) bool {
		for _, m := range t.Pkgs[n].Truck {
			if p, ok := t.Pkgs[n+"/"+m]; ok && len(p.Emits) > 0 {
				return true
			}
		}
		return len(t.Pkgs[n].Emits) > 0
	}
	sort.SliceStable(out, func(i, j int) bool { return !backend(out[i]) && backend(out[j]) })
	return out
}

func (t *Tree) index() string {
	var b strings.Builder
	b.WriteString(header("the package files in registry/"))
	b.WriteString("# Package reference\n\n")
	b.WriteString("Every truck and package in the registry, generated from the `doc` section\n")
	b.WriteString("of each package file. Trucks are collections of packages; a program loads\n")
	b.WriteString("them with `use`. See [packages and trucks](../packages.md) for the file\n")
	b.WriteString("format.\n\n")
	b.WriteString("## The package tree\n\n")
	var walk func(name string, depth int)
	walk = func(name string, depth int) {
		f := t.Pkgs[name]
		label := link("README.md", name)
		if f.IsTruck {
			label = "**" + label + "** (truck)"
		}
		fmt.Fprintf(&b, "%s- %s — %s\n", strings.Repeat("  ", depth), label, f.Doc)
		for _, m := range f.Truck {
			if _, ok := t.Pkgs[name+"/"+m]; ok {
				walk(name+"/"+m, depth+1)
			}
		}
	}
	for _, r := range t.roots() {
		walk(r, 0)
	}
	b.WriteString("\n## How front end and back end pair up\n\n")
	b.WriteString("| syntax package | becomes |\n|---|---|\n")
	for _, n := range t.names() {
		f := t.Pkgs[n]
		if len(f.Syntax) == 0 {
			continue
		}
		var to string
		switch {
		case f.Expand != nil:
			var needs []string
			for _, nd := range f.Needs {
				needs = append(needs, link("README.md", nd))
			}
			to = "expands into " + strings.Join(needs, ", ")
		default:
			var backs []string
			for _, bn := range t.backends(f.Kind()) {
				backs = append(backs, link("README.md", bn))
			}
			to = strings.Join(backs, ", ")
			if to == "" {
				to = "*(no backend package)*"
			}
		}
		fmt.Fprintf(&b, "| %s | %s |\n", link("README.md", n), to)
	}
	return b.String()
}

// backends lists packages with emit sections that translate kind.
func (t *Tree) backends(kind string) []string {
	var out []string
	for _, n := range t.names() {
		f := t.Pkgs[n]
		if len(f.Emits) > 0 && f.Kind() == kind {
			out = append(out, n)
		}
	}
	return out
}

// fronts lists syntax packages whose nodes kind translates.
func (t *Tree) fronts(kind string) []string {
	var out []string
	for _, n := range t.names() {
		f := t.Pkgs[n]
		if len(f.Syntax) > 0 && f.Expand == nil && f.Kind() == kind {
			out = append(out, n)
		}
	}
	return out
}

// usedBy lists packages that need, include or contain name.
func (t *Tree) usedBy(name string) []string {
	var out []string
	kind := pkgfile.Kind(name)
	for _, n := range t.names() {
		f := t.Pkgs[n]
		hit := false
		for _, nd := range f.Needs {
			hit = hit || nd == name
		}
		if path.Dir(n) == path.Dir(name) && len(f.Emits) > 0 {
			for _, e := range f.Emits {
				for _, l := range e.Lines {
					if strings.HasPrefix(l, "@") && strings.Fields(l[1:])[0] == kind {
						hit = true
					}
				}
			}
		}
		if hit && n != name {
			out = append(out, n)
		}
	}
	return out
}

func slotRows(es []pkgfile.Elem, optional bool, rows *[]string) {
	for _, e := range es {
		if e.Optional != nil {
			slotRows(e.Optional, true, rows)
		}
		if e.Slot == nil {
			continue
		}
		typ := e.Slot.Arg
		switch {
		case e.Slot.Kind == "newvar" && typ != "":
			typ = "type of `" + typ + "`"
		case e.Slot.Kind != "expr" && e.Slot.Kind != "var" && e.Slot.Kind != "newvar":
			typ = "—"
		case typ == "":
			typ = "any"
		default:
			typ = "`" + typ + "`"
		}
		opt := ""
		if optional {
			opt = " (optional)"
		}
		*rows = append(*rows, fmt.Sprintf("| `%s`%s | %s | %s |", e.Slot.Name, opt, slotKindDesc[e.Slot.Kind], typ))
	}
}

var slotKindDesc = map[string]string{
	"expr": "expression", "block": "block of statements", "newvar": "new variable name",
	"var": "existing variable", "ident": "name", "func": "function name (called)",
	"newfunc": "function name (defined)", "args": "argument list", "params": "parameter list",
}

func (t *Tree) page(name string) string {
	f := t.Pkgs[name]
	var b strings.Builder
	b.WriteString(header(f.Origin))
	fmt.Fprintf(&b, "# %s\n\n", name)
	if f.Doc != "" {
		fmt.Fprintf(&b, "> %s\n\n", f.Doc)
	}

	var meta []string
	if path.Dir(name) != "." {
		meta = append(meta, "truck "+link(name, path.Dir(name)))
	}
	src, _ := filepath.Rel(path.Dir("docs/registry/"+name), f.Origin)
	meta = append(meta, fmt.Sprintf("[source](%s)", filepath.ToSlash(src)))
	switch {
	case f.IsTruck:
		meta = append(meta, "truck")
	case len(f.Syntax) > 0 && f.Expand == nil:
		for _, bn := range t.backends(f.Kind()) {
			meta = append(meta, "translated by "+link(name, bn))
		}
	case len(f.Emits) > 0:
		for _, fn := range t.fronts(f.Kind()) {
			meta = append(meta, "translates "+link(name, fn))
		}
	}
	b.WriteString(strings.Join(meta, " · ") + "\n\n")

	if len(f.DocBody) > 0 {
		b.WriteString(strings.Join(f.DocBody, "\n") + "\n\n")
	}

	if f.IsTruck {
		b.WriteString("## Packages\n\n| package | summary |\n|---|---|\n")
		for _, m := range f.Truck {
			full := name + "/" + m
			doc := ""
			if p, ok := t.Pkgs[full]; ok {
				doc = p.Doc
			}
			fmt.Fprintf(&b, "| %s | %s |\n", link(name, full), strings.ReplaceAll(doc, "|", "\\|"))
		}
		b.WriteString("\n")
	}

	for _, s := range f.Syntax {
		b.WriteString("## Syntax\n\n")
		kind := "`" + s.Kind + "`"
		if s.Prec > 0 {
			assoc := "left"
			if s.Right {
				assoc = "right"
			}
			kind += fmt.Sprintf(", precedence %d, %s-associative", s.Prec, assoc)
		}
		var flags []string
		if s.Place {
			flags = append(flags, "`place`")
		}
		if s.Return {
			flags = append(flags, "`return`")
		}
		if s.Loop {
			flags = append(flags, "`loop`")
		}
		if s.InLoop {
			flags = append(flags, "`inloop`")
		}
		if s.Top {
			flags = append(flags, "`top`")
		}
		if len(flags) > 0 {
			kind += "; flags " + strings.Join(flags, ", ")
		}
		b.WriteString("Kind: " + kind + "\n\n```\n")
		for _, p := range s.Patterns {
			b.WriteString(p.String() + "\n")
		}
		b.WriteString("```\n\n")
		var rows []string
		for _, p := range s.Patterns {
			slotRows(p.Elems, false, &rows)
		}
		if len(rows) > 0 {
			b.WriteString("| slot | takes | type |\n|---|---|---|\n" + strings.Join(rows, "\n") + "\n\n")
		}
		for _, p := range s.Patterns {
			if p.Result != "" {
				res := "`" + p.Result + "`"
				if strings.HasPrefix(p.Result, "{") {
					res = "the type of `" + strings.Trim(p.Result, "{}") + "`"
				}
				b.WriteString("Produces: " + res + "\n\n")
				break
			}
		}
	}

	if len(f.Needs) > 0 {
		b.WriteString("## Needs\n\n")
		for _, n := range f.Needs {
			fmt.Fprintf(&b, "- %s\n", link(name, n))
		}
		b.WriteString("\n")
	}

	if f.Expand != nil {
		b.WriteString("## Expands to\n\nThis package has no backend: each use is rewritten to the following\nsource, with `{slot}` replaced by what was written there, and compiled again.\n\n```\n")
		b.WriteString(strings.Join(f.Expand, "\n") + "\n```\n\n")
	}

	if f.Code != nil {
		b.WriteString("## Library code\n\nMerged into every program that uses this package.\n\n```\n")
		b.WriteString(strings.Join(f.Code, "\n") + "\n```\n\n")
	}

	if len(f.Emits) > 0 {
		b.WriteString("## Emit variants\n\nThe first variant whose condition holds is used.\n\n")
		for _, e := range f.Emits {
			title := "emit"
			if e.Section != "" {
				title += " " + e.Section
			}
			if c := e.Cond; c != nil {
				switch c.Op {
				case "type":
					title += " when " + c.Slot + " " + c.Arg
				case "simple", "empty":
					title += " when " + c.Slot + " " + c.Op
				default:
					title += " when " + c.Slot + " " + c.Op + " " + c.Arg
				}
			}
			fmt.Fprintf(&b, "### `%s`\n\n```nasm\n%s\n```\n\n", title, strings.Join(e.Lines, "\n"))
		}
		var incs []string
		seen := map[string]bool{}
		for _, e := range f.Emits {
			for _, l := range e.Lines {
				if strings.HasPrefix(l, "@") {
					if inc := path.Dir(name) + "/" + strings.Fields(l[1:])[0]; !seen[inc] {
						seen[inc] = true
						incs = append(incs, link(name, inc))
					}
				}
			}
		}
		if len(incs) > 0 {
			b.WriteString("Includes: " + strings.Join(incs, ", ") + "\n\n")
		}
	}
	if len(f.Data) > 0 {
		fmt.Fprintf(&b, "## Data (per use)\n\n```nasm\n%s\n```\n\n", strings.Join(f.Data, "\n"))
	}
	if len(f.Support) > 0 {
		fmt.Fprintf(&b, "## Support code (once per program)\n\n```nasm\n%s\n```\n\n", strings.Join(f.Support, "\n"))
	}
	if users := t.usedBy(name); len(users) > 0 {
		var ls []string
		for _, u := range users {
			ls = append(ls, link(name, u))
		}
		b.WriteString("## Used by\n\n" + strings.Join(ls, ", ") + "\n")
	}
	return strings.TrimRight(b.String(), "\n") + "\n"
}

// IndexFile is the registry's list of packages, for tools that read the
// registry over HTTP, where a folder can't be listed.
const IndexFile = "index.txt"

// PackageIndex renders IndexFile: every package name, one per line, sorted.
func (t *Tree) PackageIndex() string {
	var b strings.Builder
	b.WriteString("// Every package in this registry, one name per line, for tools that read\n")
	b.WriteString("// it over HTTP (such as tools/treestat.pkg). Generated by\n")
	b.WriteString("// `go run ./cmd/pkgdoc`; don't edit it.\n")
	for _, n := range t.names() {
		b.WriteString(n + "\n")
	}
	return b.String()
}

// Write renders the reference into outDir, removing stale pages.
func (t *Tree) Write(outDir string) error {
	files := t.Generate()
	if err := os.RemoveAll(outDir); err != nil {
		return err
	}
	for p, content := range files {
		full := filepath.Join(outDir, filepath.FromSlash(p))
		if err := os.MkdirAll(filepath.Dir(full), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(full, []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}
